// TestRitualTasksImprovementIdenticalScheduleNoOp verifies that changing a ritual's
// recurrence schedule to an identical rule is a no-op: no instances are removed,
// detached, or newly created, and the schedule_version remains unchanged.
func TestRitualTasksImprovementIdenticalScheduleNoOp(t *testing.T) {
	t.Parallel()
	w := newTestWorld(t)
	owner := w.withOwner()
	proj := w.createProjectWithMode(owner, "No-op Schedule Project", uniqueProjectKey("NOOP"), rpcv1.CollaborationMode_COLLABORATION_MODE_RITUAL)
	def := w.createRitualDefinition(owner, proj.ID, "No-op Ritual", dailyRecurrenceRule())
	w.generateRitualInstances(owner)

	defBefore := w.getRitualDefinition(owner, def.Id)
	initialInstances := w.listTasksWithKind(owner, proj.ID, ptr(rpcv1.TaskKind_TASK_KIND_RITUAL_INSTANCE))
	instanceCountBefore := len(initialInstances)

	t.Run("when changing daily to the exact same daily rule", func(t *testing.T) {
		result := w.changeRitualDefinitionSchedule(owner, def.Id, dailyRecurrenceRule())
		defAfter := w.getRitualDefinition(owner, def.Id)
		instancesAfter := w.listTasksWithKind(owner, proj.ID, ptr(rpcv1.TaskKind_TASK_KIND_RITUAL_INSTANCE))

		t.Run("returns zero impact counts", func(t *testing.T) {
			assert.Equal(t, int32(0), result.InstancesRemoved)
			assert.Equal(t, int32(0), result.InstancesDetached)
			assert.Equal(t, int32(0), result.InstancesCreated)
		})

		t.Run("does not increment schedule_version", func(t *testing.T) {
			assert.Equal(t, defBefore.ScheduleVersion, defAfter.ScheduleVersion)
		})

		t.Run("does not remove any existing instances", func(t *testing.T) {
			assert.Equal(t, instanceCountBefore, len(instancesAfter))
		})
	})
}
