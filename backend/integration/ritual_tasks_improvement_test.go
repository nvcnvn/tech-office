// TestRitualTasksImprovementLazyResources covers the lazy creation of chat channels and
// description documents for ritual instance tasks.
//
// Before this feature: every generated ritual instance had a channel and doc created at
// generation time, wasting resources for instances that may never be opened.
// After this feature: channel and doc are created on first user interaction (get task detail).
func TestRitualTasksImprovementLazyResources(t *testing.T) {
	t.Parallel()
	w := newTestWorld(t)
	owner := w.withOwner()
	proj := w.createProjectWithMode(owner, "Lazy Resource Project", uniqueProjectKey("LZRC"), rpcv1.CollaborationMode_COLLABORATION_MODE_RITUAL)
	_ = w.createRitualDefinition(owner, proj.ID, "Daily Check", dailyRecurrenceRule())
	w.generateRitualInstances(owner)

	tasks := w.listTasksWithKind(owner, proj.ID, ptr(rpcv1.TaskKind_TASK_KIND_RITUAL_INSTANCE))
	require.NotEmpty(t, tasks, "expected ritual instances to be generated")

	t.Run("when a ritual instance is generated by the scheduler", func(t *testing.T) {
		task := tasks[0]

		t.Run("it has no chat channel (lazy — not yet created)", func(t *testing.T) {
			// FR-001: System MUST NOT create a chat channel when generating an instance.
			assert.Empty(t, task.ChannelId,
				"ritual instance should have no channel until first user interaction")
		})

		t.Run("it has no description document (lazy — not yet created)", func(t *testing.T) {
			// FR-002: System MUST NOT create a description document when generating an instance.
			assert.Empty(t, task.DescriptionDocumentId,
				"ritual instance should have no description doc until first user interaction")
		})
	})

	t.Run("when a user opens a ritual instance detail view", func(t *testing.T) {
		task := tasks[1]
		// GetTask triggers EnsureTaskResources for ritual instances.
		fetched := w.getTask(owner, task.Id)

		// FR-003: System MUST create channel when user first accesses the detail view.
		t.Run("the task now has a chat channel created on demand", func(t *testing.T) {
			assert.NotEmpty(t, fetched.ChannelId,
				"first GetTask should trigger lazy channel creation")
		})

		// FR-003: System MUST create description doc when user first accesses detail view.
		t.Run("the task now has a description document created on demand", func(t *testing.T) {
			assert.NotEmpty(t, fetched.DescriptionDocumentId,
				"first GetTask should trigger lazy description doc creation")
		})

		// FR-005: Lazy resource creation MUST be idempotent.
		t.Run("subsequent GetTask calls return the same channel and document", func(t *testing.T) {
			fetchedAgain := w.getTask(owner, task.Id)
			assert.Equal(t, fetched.ChannelId, fetchedAgain.ChannelId,
				"channel ID must be stable across repeated GetTask calls")
			assert.Equal(t, fetched.DescriptionDocumentId, fetchedAgain.DescriptionDocumentId,
				"description doc ID must be stable across repeated GetTask calls")
		})
	})

	t.Run("when a standard task is created", func(t *testing.T) {
		standardProj := w.createProject(owner, "Standard Task Project", uniqueProjectKey("STLZ"))
		level0 := levelByDepth(standardProj.Levels, 0)
		require.NotNil(t, level0)
		standardTask := w.createTask(owner, standardProj.ID, "Standard Task", level0.Id)

		// FR-006: Standard tasks MUST continue to create channels eagerly.
		t.Run("it still has a channel created eagerly (no behavior change)", func(t *testing.T) {
			assert.NotEmpty(t, standardTask.ChannelId,
				"standard tasks should still get a channel at creation time")
		})

		// FR-006: Standard tasks MUST continue to create docs eagerly.
		t.Run("it still has a description document created eagerly (no behavior change)", func(t *testing.T) {
			assert.NotEmpty(t, standardTask.DescriptionDocumentId,
				"standard tasks should still get a description doc at creation time")
		})
	})
}

// TestRitualTasksImprovementConcurrentAccess verifies that concurrent GetTask calls
// for the same uninitialized ritual instance do not produce duplicate channels or documents.
func TestRitualTasksImprovementConcurrentAccess(t *testing.T) {
	t.Parallel()
	w := newTestWorld(t)
	owner := w.withOwner()
	emp := w.withEmployee()
	proj := w.createProjectWithMode(owner, "Concurrent Access Project", uniqueProjectKey("CONC"), rpcv1.CollaborationMode_COLLABORATION_MODE_RITUAL)
	w.addProjectMember(owner, proj.ID, emp.ID, rpcv1.ProjectMemberRole_PROJECT_MEMBER_ROLE_MEMBER)
	_ = w.createRitualDefinition(owner, proj.ID, "Concurrent Ritual", dailyRecurrenceRule())
	w.generateRitualInstances(owner)

	tasks := w.listTasksWithKind(owner, proj.ID, ptr(rpcv1.TaskKind_TASK_KIND_RITUAL_INSTANCE))
	require.NotEmpty(t, tasks)
	taskID := tasks[0].Id

	// Both callers trigger EnsureTaskResources; only one should create resources.
	t.Run("when two users open the same ritual instance simultaneously", func(t *testing.T) {
		taskFromOwner := w.getTask(owner, taskID)
		taskFromEmp := w.getTask(emp, taskID)

		// FR-005: Idempotent — concurrent requests produce exactly one channel.
		t.Run("both see the same channel ID (no duplicate channel created)", func(t *testing.T) {
			assert.NotEmpty(t, taskFromOwner.ChannelId)
			assert.Equal(t, taskFromOwner.ChannelId, taskFromEmp.ChannelId,
				"concurrent callers must see the same channel — no duplicate created")
		})

		// FR-005: Idempotent — concurrent requests produce exactly one document.
		t.Run("both see the same document ID (no duplicate document created)", func(t *testing.T) {
			assert.NotEmpty(t, taskFromOwner.DescriptionDocumentId)
			assert.Equal(t, taskFromOwner.DescriptionDocumentId, taskFromEmp.DescriptionDocumentId,
				"concurrent callers must see the same doc — no duplicate created")
		})
	})
}

// TestRitualTasksImprovementScheduleChangeImpact verifies the preview endpoint that
// returns impact counts before a schedule change is applied.
func TestRitualTasksImprovementScheduleChangeImpact(t *testing.T) {
	t.Parallel()
	w := newTestWorld(t)
	owner := w.withOwner()
	proj := w.createProjectWithMode(owner, "Impact Preview Project", uniqueProjectKey("IMPC"), rpcv1.CollaborationMode_COLLABORATION_MODE_RITUAL)
	def := w.createRitualDefinition(owner, proj.ID, "Daily Check", dailyRecurrenceRule())
	w.generateRitualInstances(owner)

	t.Run("when querying impact of changing daily to weekly", func(t *testing.T) {
		impact := w.getScheduleChangeImpact(owner, def.Id, weeklyRecurrenceRule())

		// FR-013: Impact preview must include count of instances to be removed.
		t.Run("it returns the count of future untouched instances to be removed", func(t *testing.T) {
			assert.Greater(t, impact.InstancesToRemove, int32(0),
				"daily ritual should have multiple future untouched instances")
		})

		// FR-013: Impact preview must include count of instances to be kept as standalone.
		t.Run("it returns the count of instances that would be detached", func(t *testing.T) {
			// Initially all are untouched, so touched count should be 0.
			assert.Equal(t, int32(0), impact.InstancesToDetach,
				"no instances have been touched yet, so detach count should be 0")
		})

		// FR-013: Impact preview must include count of new instances to be created.
		t.Run("it returns an estimate of new instances to be created", func(t *testing.T) {
			assert.Greater(t, impact.InstancesToCreate, int32(0),
				"new weekly instances should be estimated")
		})
	})

	t.Run("when one future instance becomes touched (user opens its detail)", func(t *testing.T) {
		tasks := w.listTasksWithKind(owner, proj.ID, ptr(rpcv1.TaskKind_TASK_KIND_RITUAL_INSTANCE))
		require.NotEmpty(t, tasks)
		w.getTask(owner, tasks[0].Id) // triggers lazy resource creation → task becomes "touched"
		impact := w.getScheduleChangeImpact(owner, def.Id, weeklyRecurrenceRule())

		t.Run("the detach count increases by 1 for the now-touched instance", func(t *testing.T) {
			assert.Equal(t, int32(1), impact.InstancesToDetach,
				"one instance was touched (channel created), so detach count should be 1")
		})

		t.Run("the remove count decreases by 1 correspondingly", func(t *testing.T) {
			// Total = untouched + touched; touched one moved from remove → detach bucket.
			assert.GreaterOrEqual(t, impact.InstancesToRemove, int32(0))
		})
	})
}

// TestRitualTasksImprovementScheduleChangeUntouched verifies that a schedule change
// correctly soft-deletes future untouched instances.
