// TestRitualTasksImprovementRapidScheduleChanges verifies that repeated schedule changes
// apply the "Clean Slate Forward" logic consistently (idempotent design).
func TestRitualTasksImprovementRapidScheduleChanges(t *testing.T) {
	t.Parallel()
	w := newTestWorld(t)
	owner := w.withOwner()
	proj := w.createProjectWithMode(owner, "Rapid Change Project", uniqueProjectKey("RPDC"), rpcv1.CollaborationMode_COLLABORATION_MODE_RITUAL)
	def := w.createRitualDefinition(owner, proj.ID, "Rapid Change Ritual", dailyRecurrenceRule())
	w.generateRitualInstances(owner)

	t.Run("when changing daily→weekly→bi-weekly in sequence", func(t *testing.T) {
		// First change: daily → weekly
		result1 := w.changeRitualDefinitionSchedule(owner, def.Id, weeklyRecurrenceRule())
		defAfterFirst := w.getRitualDefinition(owner, def.Id)
		// Second change: weekly → bi-weekly (every 2 weeks)
		result2 := w.changeRitualDefinitionSchedule(owner, def.Id, biWeeklyRecurrenceRule())
		defAfterSecond := w.getRitualDefinition(owner, def.Id)

		t.Run("each change increments the schedule_version", func(t *testing.T) {
			assert.Equal(t, int32(2), defAfterFirst.ScheduleVersion)
			assert.Equal(t, int32(3), defAfterSecond.ScheduleVersion)
		})

		t.Run("each change generates new instances matching the new pattern", func(t *testing.T) {
			assert.Greater(t, result1.InstancesCreated, int32(0))
			assert.Greater(t, result2.InstancesCreated, int32(0))
			// Bi-weekly should produce fewer instances than weekly over same window
			assert.LessOrEqual(t, result2.InstancesCreated, result1.InstancesCreated,
				"bi-weekly should produce fewer or equal instances than weekly")
		})

		t.Run("final instances follow the bi-weekly pattern", func(t *testing.T) {
			assert.Equal(t, rpcv1.RecurrenceType_RECURRENCE_TYPE_WEEKLY, defAfterSecond.RecurrenceRule.Type)
			assert.Equal(t, int32(2), defAfterSecond.RecurrenceRule.Interval,
				"bi-weekly = interval of 2 weeks")
		})
	})
}

