// TestRitualTasksImprovementScheduleChangeAtomicity verifies that the schedule change
// operation is atomic — if anything fails, no partial changes are persisted.
func TestRitualTasksImprovementScheduleChangeAtomicity(t *testing.T) {
	t.Parallel()
	// FR-012: The entire schedule change operation executes atomically.
	// This is a structural test — we rely on the transaction boundary in the Connect layer.
	// The integration test verifies the observable effect: after a successful change,
	// ALL expected modifications are present (soft-deletes, detaches, new instances, version bump).
	w := newTestWorld(t)
	owner := w.withOwner()
	proj := w.createProjectWithMode(owner, "Atomicity Project", uniqueProjectKey("ATOM"), rpcv1.CollaborationMode_COLLABORATION_MODE_RITUAL)
	def := w.createRitualDefinition(owner, proj.ID, "Atomic Daily", dailyRecurrenceRule())
	w.generateRitualInstances(owner)
	beforeVersion := w.getRitualDefinition(owner, def.Id).ScheduleVersion
	beforeTasks := w.listTasksWithKind(owner, proj.ID, ptr(rpcv1.TaskKind_TASK_KIND_RITUAL_INSTANCE))
	result := w.changeRitualDefinitionSchedule(owner, def.Id, weeklyRecurrenceRule())

	// FR-012: Atomic — all or nothing.
	t.Run("after a successful schedule change, all state changes are consistently applied", func(t *testing.T) {
		afterDef := w.getRitualDefinition(owner, def.Id)
		afterTasks := w.listTasksWithKind(owner, proj.ID, ptr(rpcv1.TaskKind_TASK_KIND_RITUAL_INSTANCE))
		assert.Equal(t, beforeVersion+1, afterDef.ScheduleVersion,
			"schedule_version must be incremented as part of the atomic operation")
		assert.Equal(t, rpcv1.RecurrenceType_RECURRENCE_TYPE_WEEKLY, afterDef.RecurrenceRule.Type,
			"recurrence rule must be updated as part of the atomic operation")
		assert.Greater(t, result.InstancesRemoved, int32(0),
			"soft-deleted instances must be reflected in response")
		assert.Greater(t, result.InstancesCreated, int32(0),
			"new instances must be generated as part of the atomic operation")
		assert.NotEqual(t, len(beforeTasks), len(afterTasks),
			"task list must change after schedule change (old removed, new generated)")
	})
}

