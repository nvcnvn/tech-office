// injectPastRitualInstance creates a ritual instance task with a past scheduled_date
// by first generating instances normally, then backdating one via direct SQL.
func (w *testWorld) injectPastRitualInstance(actor testUser, proj projectResult, def *rpcv1.RitualDefinition) string {
	w.t.Helper()
	// Generate instances so we have real task rows.
	w.generateRitualInstances(actor)
	tasks := w.listTasksWithKind(actor, proj.ID, ptr(rpcv1.TaskKind_TASK_KIND_RITUAL_INSTANCE))
	require.NotEmpty(w.t, tasks, "need at least one ritual instance to backdate")

	pastTaskID := tasks[0].Id
	pastDate := time.Now().AddDate(0, 0, -7)
	_, err := globalDB.Exec(context.Background(),
		`UPDATE collaboration.task SET scheduled_date = $1 WHERE id = $2 AND organization_id = $3`,
		pastDate, dbuuid.MustParse(pastTaskID), actor.OrgID,
	)
	require.NoError(w.t, err)
	return pastTaskID
}

